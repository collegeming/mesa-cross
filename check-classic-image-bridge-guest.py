for name in ['goldfish_vk_extension_structs_guest.h', 'goldfish_vk_marshaling_guest.h', 'goldfish_vk_reserved_marshaling_guest.h']:
    header = (root / 'src/gfxstream/guest/vulkan_enc/autogenerated' / name).read_text()
    assert '#include "vk_android_native_buffer_gfxstream.h"' in header, name
for name in ['goldfish_vk_extension_structs_guest.cpp', 'goldfish_vk_marshaling_guest.cpp', 'goldfish_vk_reserved_marshaling_guest.cpp']:
    generated = (root / 'src/gfxstream/guest/vulkan_enc/autogenerated' / name).read_text()
    assert 'case VK_STRUCTURE_TYPE_NATIVE_BUFFER_ANDROID:' in generated, name
assert 'VkNativeBufferANDROID cib1QueryMarker{}' in rt
assert 'cib1QueryMarker.pNext = localImageFormatInfo.pNext' in rt
assert 'cib1QueryMarker.usage2.consumer = UINT64_C(0x4349423100000001)' in rt
assert 'cib1Query = mCaps.classicImageBridgeAck && cib1ChainKnown && cib1Ext' in rt
assert '.at(' not in rt[rt.index('VkResult ResourceTracker::on_vkBindImageMemory('):rt.index('VkResult ResourceTracker::on_vkCreateBuffer(')]
for text in ['#include "vk_android_native_buffer_gfxstream.h"',
             'mCaps.classicImageBridgeAck && extImgCiPtr',
             'UINT64_C(0x4349423100000001)',
             'cib1Native.handle = &cib1ResourceId',
             'cib1Native.stride = static_cast<int>(stride / 4)',
             'cib1Native.usage2.producer = 0',
             '(uint64_t(width) * 4 + 15) & ~uint64_t(15)',
             'height > UINT32_MAX / row',
             'cib1Views(pCreateInfo->format, pCreateInfo->flags, cib1ViewsInfo)',
             'VK_IMAGE_CREATE_ALIAS_BIT | VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT',
             'if (!list) return true;',
             'VkFormat cib1ViewFormats[2] = {};',
             'else if (pCreateInfo->flags & VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT)',
             'cib1ViewFormats[0] = pCreateInfo->format;',
             'cib1ViewFormats[1] = srgb;',
             'cib1ViewList.sType = VK_STRUCTURE_TYPE_IMAGE_FORMAT_LIST_CREATE_INFO;',
             'cib1ViewList.viewFormatCount = 2;',
             'cib1ViewList.pViewFormats = cib1ViewFormats;',
             'list->viewFormatCount > 2',
             'gpu->createResource(width, height, stride, bytes, vf,',
             'cib1Resource->wait()',
             'if (extImgCiPtr && !cib1)',
             '!cib1 && (pCreateInfo->tiling == VK_IMAGE_TILING_DRM_FORMAT_MODIFIER_EXT)',
             'memReqs.alignment != 1', 'flags == VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT',
             'info.classicBridgeResource = std::move(cib1Resource)',
             'pAllocateInfo->allocationSize != ci.baseRequirements.size',
             'local.pNext = &dedicated', 'dedicated.pNext = &cb',
             'VkImportColorBufferGOOGLE cb',
             'vk_find_struct_const(pAllocateInfo, IMPORT_MEMORY_FD_INFO_KHR)',
             'cib1BindIdentity(ii.classicBridgeResource != nullptr',
             'cib1RetainAllocation(image != info_VkImage.end()',
             'mi.classicBridgeBound, memoryOffset)',
             'if (result == VK_SUCCESS) mi.classicBridgeBound = true',
             'if (bindingCount != 1 || pBindInfos[i].pNext)',
             'if (deviceMemoryInfo.classicBridgeImage) return VK_ERROR_MEMORY_MAP_FAILED',
             'if (info.classicBridgeImage && !info.classicBridgeBound)',
             'VK_EXTERNAL_MEMORY_FEATURE_EXPORTABLE_BIT | VK_EXTERNAL_MEMORY_FEATURE_DEDICATED_ONLY_BIT',
             'compatibleHandleTypes != cib1Ext->handleType',
             'maxMipLevels = 1', 'maxArrayLayers = 1', 'sampleCounts = VK_SAMPLE_COUNT_1_BIT',
             'if (!cib1Query) localImageFormatInfo.usage &=']:
    assert text in rt, text
create_block = rt[rt.index('if (cib1) {'):rt.index('if (extImgCiPtr && !cib1)')]
assert 'if (cib1ViewsInfo) {' in create_block
assert 'else if (pCreateInfo->flags & VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT)' in create_block
