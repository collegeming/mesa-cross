#!/usr/bin/env python3
"""Static and model checks for the guest readback-invalidate patch.

Runs against the patched Mesa tree before the aarch64 build. It cannot execute
the C++ (the tree is cross-compiled, and the A2 scan needs a Vulkan device), so
it does two things that are still meaningful:

  * source assertions: the environment is read once, lazily, under a statically
    initialized mutex; the default is "everything on" and "0"/"off" is the only
    thing that restores the baseline; every cache operation sits behind its
    mode; the statistics counters, clock reads and the SIGUSR1 handler cannot
    run unless GFXSTREAM_GUEST_INVALIDATE_STATS=1; the only log line is the
    DEBUG-gated configuration line; the EL0/UCI probe exists so a kernel without
    UCI disables maintenance instead of taking SIGILL;
  * a model of the range math and of the environment parser, checked against the
    same edge cases the host-compiled unit test (test-guest-cache-maintenance.cpp)
    runs against the real header.

Default-on is a consequence of the parser asserted here; baseline equivalence
for "=0" is the same structure the previous revision relied on: every entry
point returns at its first statement, before any lock, iterator, pointer
dereference, clock read or counter update.
"""
import argparse
import re
import sys
from pathlib import Path

ENC = 'src/gfxstream/guest/vulkan_enc'
HEADER_REL = ENC + '/GuestCacheMaintenance.h'
RT_H_REL = ENC + '/ResourceTracker.h'
RT_CPP_REL = ENC + '/ResourceTracker.cpp'
VALIDATION_REL = ENC + '/Validation.cpp'
ENCODER_REL = ENC + '/autogenerated/VkEncoder.cpp'
EXPECTED_PATHS = {HEADER_REL, RT_H_REL, RT_CPP_REL, VALIDATION_REL, ENCODER_REL}
ENV_NAME = 'GFXSTREAM_GUEST_INVALIDATE'
STATS_ENV_NAME = 'GFXSTREAM_GUEST_INVALIDATE_STATS'
DEBUG_ENV_NAME = 'GFXSTREAM_GUEST_INVALIDATE_DEBUG'
UINT64_MAX = (1 << 64) - 1

FAILS = []


def check(condition, message):
    if condition:
        print('PASS ' + message)
    else:
        FAILS.append(message)
        print('FAIL ' + message)


def align_up(value, line=64):
    return (value + line - 1) & ~(line - 1)


def model_range(allocation_size, offset, size):
    if not allocation_size or offset >= allocation_size:
        return (0, 0)
    if size == UINT64_MAX or size > allocation_size - offset:
        end = allocation_size
    else:
        end = offset + size
    if end <= offset:
        return (0, 0)
    return (offset & ~63, align_up(end))


def model_mode(value):
    # Default on: unset or set-but-empty selects every mechanism.
    if value is None or value == '':
        return 15
    if value == '0':
        return 0
    if value == 'off':
        return 0
    if value in ('1', 'on', 'all'):
        return 15
    mode = 0
    for token in value.split(','):
        if not token:
            continue
        bit = {'a1': 1, 'a2': 2, 'cmap': 4, 'cunmap': 8}.get(token)
        if bit is None:
            return 15
        mode |= bit
    return mode or 15


def function_region(text, signature):
    start = text.index(signature)
    end = text.find('\nvoid ResourceTracker::', start + len(signature))
    if end < 0:
        end = text.find('\nVkResult ResourceTracker::', start + len(signature))
    if end < 0:
        end = len(text)
    return text[start:end]


def first_statement(region):
    body = region[region.index('{') + 1:]
    for line in body.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('//') or stripped.startswith('/*'):
            continue
        return stripped
    return ''


def previous_nonempty_line(text, needle):
    lines = text.splitlines()
    for index, line in enumerate(lines):
        if needle in line:
            for back in range(index - 1, -1, -1):
                if lines[back].strip():
                    return lines[back].strip()
    return ''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', type=Path, help='patched mesa source tree')
    parser.add_argument('--diff', type=Path, help='unified diff written by the patch script')
    args = parser.parse_args()
    root = args.root.resolve()

    header = (root / HEADER_REL).read_text(encoding='utf-8')
    rt_h = (root / RT_H_REL).read_text(encoding='utf-8')
    rt_cpp = (root / RT_CPP_REL).read_text(encoding='utf-8')
    validation = (root / VALIDATION_REL).read_text(encoding='utf-8')
    encoder = (root / ENCODER_REL).read_text(encoding='utf-8')

    # ---------------------------------------------------------------- header
    check('#if defined(__aarch64__)' in header, 'header is aarch64-guarded')
    check('dc civac, %0' in header, 'header emits dc civac for invalidate')
    check('dc cvac, %0' in header, 'header emits dc cvac for flush')
    check('dsb sy' in header, 'header emits dsb sy after maintenance')
    check('#include <vulkan' not in header and 'VkDeviceSize' not in header,
          'header stays Vulkan-independent (host unit test)')
    check('static constexpr uint64_t kGuestCacheLineSize = 64;' in header,
          'cache line size is the architectural minimum')
    check('kGuestCacheModeCMap = 1u << 2' in header, 'CMap is an independent mode bit')
    check('kGuestCacheModeCUnmap = 1u << 3' in header, 'CUnmap is an independent mode bit')
    check('kGuestCacheModeAll = kGuestCacheModeA1 | kGuestCacheModeA2 | kGuestCacheModeCMap |'
          in header, 'the "all" mask covers every mode')
    check('kGuestCacheModeStats = 1u << 31' in header,
          'the statistics flag is a separate high bit')

    # -------------------------------------------------------- default is on
    check('if (!value || !value[0]) return kGuestCacheModeAll;' in header,
          'unset or empty GFXSTREAM_GUEST_INVALIDATE enables everything')
    check("if (value[0] == '0' && !value[1]) return kGuestCacheModeOff;" in header,
          '"0" disables everything')
    check("if (value[0] == 'o' && value[1] == 'f' && value[2] == 'f' && !value[3])" in header,
          '"off" disables everything')
    check('static constexpr uint32_t guestCacheModeFromEnvValue(const char* value)' in header,
          'the parser is constexpr, so the default is a compile-time fact')
    check("while (*end && *end != ',') ++end;" in header,
          'the environment parser accepts a comma-separated list')
    check('static constexpr GuestCacheConfig guestCacheConfigFromEnvValues(' in header
          or 'static inline GuestCacheConfig guestCacheConfigFromEnvValues(' in header,
          'the mode/stats/debug word is produced by one pure function')
    check('if (config.stats) config.mode |= kGuestCacheModeStats;' in header,
          'statistics ride in the same resolved word as the mode')

    # --------------------------------------------------- one-time, no static init
    check(header.count(f'getenv("{ENV_NAME}")') == 1,
          f'env {ENV_NAME} read exactly once')
    check(header.count(f'getenv("{STATS_ENV_NAME}")') == 1,
          f'env {STATS_ENV_NAME} read exactly once')
    check(header.count(f'getenv("{DEBUG_ENV_NAME}")') == 1,
          f'env {DEBUG_ENV_NAME} read exactly once')
    resolve_region = header[header.index('static inline uint32_t guestCacheResolveConfig()'):]
    resolve_region = resolve_region[:resolve_region.index('\n}')]
    check(resolve_region.count('getenv(') == 3,
          'all three environment reads live in the one-time resolver')
    check('static std::atomic<uint32_t> resolved{kGuestCacheConfigUnparsed};' in header,
          'the parsed word is cached in one constant-initialized atomic')
    check('static pthread_mutex_t mutex = PTHREAD_MUTEX_INITIALIZER;' in header,
          'the one-time parse is serialized by a statically initialized mutex')
    check('static const uint32_t mode =' not in header and 'static const uint32_t mode =' not in rt_cpp,
          'no static const initializer decides the mode')
    check('static GuestCacheCounters counters;' in header and
          '\n    static GuestCacheCounters counters;' in header,
          'the counters are function-local (no dynamic initialization)')
    check(header.count('pthread_mutex_lock(&mutex);') == 1 and
          header.count('pthread_mutex_unlock(&mutex);') == 1,
          'the slow path takes and releases the init mutex')

    # -------------------------------------------------------- UCI capability
    check('guestCacheProbeEl0Maintenance' in header, 'EL0/UCI capability probe present')
    check('sigsetjmp(guestCacheProbeJump, 1)' in header and 'siglongjmp(guestCacheProbeJump, 1)' in header,
          'the probe recovers from the illegal-instruction fault with siglongjmp')
    check('reinterpret_cast<uintptr_t>(info->si_addr) == guestCacheProbePc' in header,
          'the SIGILL handler only recovers from the probed instruction')
    check('if ((mode & kGuestCacheModeAll) != kGuestCacheModeOff) {' in header,
          'the probe is skipped when maintenance is disabled (no dc at all)')
    check('if (el0 == 0) mode = kGuestCacheModeOff;' in header,
          'a kernel without UCI falls back to the baseline instead of taking SIGILL')

    # ------------------------------------------------------------- statistics
    check('GUEST-CMO-STATS maps=' in header, 'the statistics line has the fixed prefix')
    check('std::atexit(&guestCacheStatsPrint);' in header, 'counters print at process exit')
    check('sigaction(SIGUSR1, &action, nullptr);' in header and
          'action.sa_handler = &guestCacheStatsSignalHandler;' in header,
          'SIGUSR1 prints a snapshot')
    check('clock_gettime(CLOCK_MONOTONIC, &ts)' in header, 'timing uses CLOCK_MONOTONIC')
    check(header.count('clock_gettime(') == 1,
          'the clock is read in exactly one place')
    check(header.count('fetch_add') == 5, 'five counter updates (maps/unmaps/waits/bytes/ns)')
    check('::write(STDERR_FILENO' in header, 'the statistics line is written to stderr')
    check('const ssize_t written = ::write(' in header,
          'the dump uses write(2), which the signal handler may call')

    # ---------------------------------------------------- statistics are opt-in
    check(rt_cpp.count('guestCacheStatsRecord(') == 3,
          'three statistics call sites (A1, A2, map/unmap helper)')
    check(rt_cpp.count('guestCacheStart = guestCacheStats ? guestCacheNowNs() : 0;') == 3,
          'the clock is read only behind the stats flag')
    check(rt_cpp.count('guestCacheNowNs()') == 6 and
          rt_cpp.count('guestCacheNowNs()') == 2 * rt_cpp.count('guestCacheStatsRecord('),
          'every guestCacheNowNs() is part of a stats-guarded statement')
    for needle in ('guestCacheStatsRecord(kGuestCacheStatNone',
                   'guestCacheStatsRecord(kGuestCacheStatWait',
                   'guestCacheStatsRecord(static_cast<GuestCacheStatEvent>(statEvent)'):
        check(previous_nonempty_line(rt_cpp, needle) == 'if (guestCacheStats)',
              f'{needle.split("(")[0]} is guarded by if (guestCacheStats)')
    check('fetch_add' not in rt_cpp, 'the callers never touch the counters directly')
    check(rt_cpp.count('guestCacheMaintenanceMode()') >= 3,
          'the entry points still gate on the cached mode word')

    # -------------------------------------------------------- only one log line
    check(header.count('printf') == 1, 'the header contains exactly one printf-family call')
    check(previous_nonempty_line(header, 'std::fprintf(stderr, "GUEST-CMO-CONFIG') != '',
          'the single log line is inside guestCacheDebugLog')
    check('if (config.debug) guestCacheDebugLog(' in header,
          'the single log line only runs with GFXSTREAM_GUEST_INVALIDATE_DEBUG=1')

    # ----------------------------------------------------------- declarations
    check('void guestCacheMaintainMappedRanges(const VkMappedMemoryRange* pMemoryRanges,' in rt_h,
          'A1 helper declared')
    check('void guestCacheInvalidateMappedCoherent();' in rt_h, 'A2 helper declared')
    check('void guestCacheMaintainMappedAllocation(VkDeviceMemory memory, uint64_t offset, '
          'uint64_t size,' in rt_h, 'CMap/CUnmap helper declared')
    check('bool invalidate, uint32_t statEvent);' in rt_h,
          'the mapped-range helper carries its statistic bucket')
    check('uint64_t guestCacheMappedOffset = 0;' in rt_h,
          'VkDeviceMemory_Info records the map offset')
    check('uint64_t guestCacheMappedSize = 0;' in rt_h,
          'VkDeviceMemory_Info records the map size')
    check('bool guestCacheMapped = false;' in rt_h,
          'VkDeviceMemory_Info records that a map actually happened')

    # ------------------------------------------------------------ A1 entry
    a1 = function_region(rt_cpp, 'void ResourceTracker::guestCacheMaintainMappedRanges(')
    check(first_statement(a1) == 'if (!(guestCacheMaintenanceMode() & kGuestCacheModeA1)) return;',
          'A1 gate is the first statement (no state touched when off)')
    check('std::lock_guard<std::recursive_mutex> lock(mLock);' in a1, 'A1 takes the tracker lock')
    check('if (!memoryInfo.ptr) continue;' in a1, 'A1 skips unmapped allocations')
    check('guestCacheRangeForMappedMemory(' in a1, 'A1 clamps offset/size against allocationSize')
    check('guestCacheCleanLine(' in a1 and 'guestCacheCleanAndInvalidateLine(' in a1,
          'A1 performs cvac on flush and civac on invalidate')
    check('range.begin >= range.end' in a1, 'A1 skips empty ranges')
    check('if (maintained) guestCacheSync();' in a1, 'A1 only issues dsb after real work')

    # ------------------------------------------------------------ A2 entry
    a2 = function_region(rt_cpp, 'void ResourceTracker::guestCacheInvalidateMappedCoherent(')
    check(first_statement(a2) ==
          'if (!(guestCacheMaintenanceMode() & kGuestCacheModeA2)) return;',
          'A2 gate is the first statement (no state touched when off)')
    check('if (!memoryInfo.ptr || !memoryInfo.allocationSize) continue;' in a2,
          'A2 skips unmapped and zero-size allocations')
    check('memProps.memoryTypes[memoryInfo.memoryTypeIndex].propertyFlags' in a2,
          'A2 reads the device-reported memory type flags')
    check('VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT' in a2,
          'A2 filters to declared HOST_VISIBLE|HOST_COHERENT')
    check('offset < memoryInfo.allocationSize' in a2,
          'A2 is bounded by the allocation size')
    check('if (invalidated) guestCacheSync();' in a2, 'A2 only issues dsb after real work')
    check('guestCacheBytes += memoryInfo.allocationSize;' in a2,
          'A2 counts the bytes it actually scanned')

    # ------------------------------------------------------- CMap/CUnmap paths
    map_func = function_region(rt_cpp, 'VkResult ResourceTracker::on_vkMapMemory(')
    check('uint64_t guestCacheLimit = deviceMemoryInfo.allocationSize;' in map_func,
          'CMap/CUnmap resolve the map bound from the allocation size')
    check('guestCacheLimit = mapSize > offset ? mapSize - offset : 0;' in map_func,
          'the export route uses the host-reported blob size as the bound')
    check('*ppData = deviceMemoryInfo.ptr + offset;' in map_func,
          'the recorded range starts at the pointer handed to the application')
    check('deviceMemoryInfo.guestCacheMappedOffset = offset;' in map_func,
          'CMap/CUnmap record the map offset')
    check('deviceMemoryInfo.guestCacheMappedSize = size;' in map_func,
          'CMap/CUnmap record the map size')
    check('deviceMemoryInfo.guestCacheMappedLimit = guestCacheLimit;' in map_func,
          'CMap/CUnmap record the clamp limit')
    check('guestCacheMaintainMappedAllocation(memory, offset, size, guestCacheLimit,' in map_func,
          'CMap invalidates before vkMapMemory returns the pointer')
    check('/*invalidate=*/true, kGuestCacheStatMap' in map_func,
          'CMap uses civac (clean+invalidate) and counts as a map')

    unmap_func = function_region(rt_cpp, 'void ResourceTracker::on_vkUnmapMemory(')
    check(first_statement(unmap_func) ==
          'if (!(guestCacheMaintenanceMode() & kGuestCacheModeCUnmap)) return;',
          'CUnmap gate is the first statement (no state touched when off)')
    check('if (!memoryInfo.guestCacheMapped) return;' in unmap_func,
          'CUnmap only acts on an allocation that actually went through vkMapMemory')
    check('memoryInfo.guestCacheMapped = false;' in unmap_func,
          'CUnmap clears the recorded range after one use')
    check('guestCacheMaintainMappedAllocation(memory, memoryInfo.guestCacheMappedOffset,' in unmap_func,
          'CUnmap maintains the range recorded at map time')
    check('/*invalidate=*/false, kGuestCacheStatUnmap' in unmap_func,
          'CUnmap uses cvac (clean only) and counts as an unmap')

    helper = function_region(rt_cpp,
                             'void ResourceTracker::guestCacheMaintainMappedAllocation(')
    check('std::lock_guard<std::recursive_mutex> lock(mLock);' in helper,
          'the mapped-range helper takes the tracker lock')
    check('if (!memoryInfo.ptr) return;' in helper, 'the helper skips unmapped allocations')
    check('(memProps.memoryTypes[memoryInfo.memoryTypeIndex].propertyFlags &\n'
          '          VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT)' in helper,
          'the helper skips non-host-visible allocations')
    check('guestCacheRangeForMappedMemory(limit, offset, size)' in helper,
          'the helper clamps offset/size against the map limit')
    check('guestCacheCleanLine(memoryInfo.ptr + line)' in helper and
          'guestCacheCleanAndInvalidateLine(memoryInfo.ptr + line)' in helper,
          'the helper performs cvac or civac per line')
    check('guestCacheSync();' in helper, 'the helper fences after real work')

    setinfo = function_region(rt_cpp, 'void ResourceTracker::setDeviceMemoryInfo(')
    check('info.guestCacheMapped = false;' in setinfo,
          'a reused VkDeviceMemory handle cannot inherit a stale mapped range')

    # ------------------------------------------------------------- call sites
    check(rt_cpp.count('guestCacheInvalidateMappedCoherent();') == 4,
          'A2 called from vkWaitForFences (2 Linux exits + 1 fallback) and vkQueueWaitIdle (1)')
    check(rt_cpp.count('guestCacheMaintainMappedRanges(') == 1,
          'A1 implementation is the only definition, no stray callers')
    check(rt_cpp.count('guestCacheMaintainMappedAllocation(') == 3,
          'mapped-range helper has one definition and the CMap/CUnmap call sites')
    check(validation.count('guestCacheMaintainMappedRanges(') == 2,
          'A1 called from flush and invalidate only')
    check('/*invalidate=*/false' in validation, 'flush path cleans (cvac)')
    check('/*invalidate=*/true' in validation, 'invalidate path invalidates (civac)')
    check(encoder.count('sResourceTracker->guestCacheInvalidateMappedCoherent();') == 1,
          'vkWaitSemaphores is the single encoder-side completion hook')
    check('vkWaitSemaphores_VkResult_return == VK_SUCCESS' in encoder,
          'vkWaitSemaphores hook is success-gated')
    check('waitResult == VK_SUCCESS' in rt_cpp,
          'vkWaitForFences/vkQueueWaitIdle hooks are success-gated')

    # ------------------------------------------------- added lines add no log
    if args.diff:
        diff_text = args.diff.read_text(encoding='utf-8')
        added = [line[1:] for line in diff_text.splitlines()
                 if line.startswith('+') and not line.startswith('+++')]
        log_hits = [line for line in added
                    if re.search(r'\b(mesa_log[a-z]*|printf|fprintf|puts|std::cout)\b', line)]
        check(len(log_hits) == 1 and 'GUEST-CMO-CONFIG' in log_hits[0],
              f'added lines contain only the DEBUG configuration line (got {len(log_hits)})')
        check('if (config.debug) guestCacheDebugLog(' in diff_text,
              'the configuration line is debug-gated')
        paths = set(re.findall(r'^diff --git a/(\S+) b/', diff_text, re.MULTILINE))
        check(paths == EXPECTED_PATHS,
              f'diff touches exactly the five expected files (got {sorted(paths)})')

    # ------------------------------------------------------------ model tests
    mode_cases = [
        (None, 15), ('', 15), ('0', 0), ('off', 0),
        ('a1', 1), ('a2', 2), ('cmap', 4), ('cunmap', 8),
        ('cmap,cunmap', 12), ('cunmap,cmap', 12), ('a1,cmap', 5),
        ('a1,a2,cmap,cunmap', 15), ('cmap,', 4), (',cunmap', 8),
        ('1', 15), ('on', 15), ('all', 15),
        ('A1', 15), ('a12', 15), ('offf', 15), ('bogus', 15), ('0,cmap', 15),
    ]
    for value, expected in mode_cases:
        check(model_mode(value) == expected,
              f'mode({value!r}) == {expected}')

    range_cases = [
        ('zero size', (4096, 0, 0), (0, 0)),
        ('single byte', (4096, 0, 1), (0, 64)),
        ('whole allocation', (4096, 0, UINT64_MAX), (0, 4096)),
        ('whole from last line', (4096, 4096 - 1, UINT64_MAX), (4032, 4096)),
        ('last line', (4096, 4096 - 64, 64), (4032, 4096)),
        ('zero allocation', (0, 0, UINT64_MAX), (0, 0)),
        ('unresolved limit', (0, 0, 4096), (0, 0)),
        ('map at an offset', (8192, 4096, 4096), (4096, 8192)),
        ('whole from a map offset', (8192, 4096, UINT64_MAX), (4096, 8192)),
        ('offset at end', (4096, 4096, 1), (0, 0)),
        ('offset past end', (4096, 4097, 1), (0, 0)),
        ('offset is u64 max', (4096, UINT64_MAX, UINT64_MAX), (0, 0)),
        ('offset+size overflows', (4096, 4000, UINT64_MAX - 1), (3968, 4096)),
        ('exact mid line', (4096, 64, 64), (64, 128)),
        ('unaligned end', (4096, 64, 1), (64, 128)),
        ('non-line-aligned allocation', (4095, 0, UINT64_MAX), (0, 4096)),
        ('one line allocation', (64, 0, 64), (0, 64)),
    ]
    for label, inputs, expected in range_cases:
        got = model_range(*inputs)
        check(got == expected, f'range {label}: {inputs} -> {got} (expected {expected})')

    # A2 covers exactly one full scan per allocation, line by line.
    check(align_up(4096) == 4096, 'page-aligned allocation needs no over-invalidation')

    if FAILS:
        print(f'\n{len(FAILS)} check(s) failed')
        return 1
    print('\nall guest readback-invalidate checks passed')
    return 0


if __name__ == '__main__':
    sys.exit(main())
